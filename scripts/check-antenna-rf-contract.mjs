import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = (p) => fs.readFileSync(p, 'utf8');
const studio = read('src/components/ThreeStudio.tsx');
const controls = read('src/components/SolverControls.tsx');
const app = read('src/App.tsx');
const types = read('src/types.ts');
const models = read('backend/models.py');
const helper = read('src/utils/antennaArrayPreview.ts');
const appSource = app;

assert.ok(studio.includes('buildPlanarArrayPreview'), 'viewport uses the array layout helper');
assert.ok(studio.includes('THREE.InstancedMesh'), 'array elements use instanced rendering');
assert.ok(studio.includes('localSteeringDirectionCanonical'), 'TX beam indicator uses local steering');
assert.ok(studio.includes('current.freqGhz') && studio.includes('current.solverOptions'), 'RF values are consumed by viewport');
assert.ok(studio.includes('beamSteeringFrame') && studio.includes('indoorBeamSteering'), 'viewport uses stored local steering metadata');
assert.ok(controls.includes('slider-beam-el'), 'beam elevation control is exposed');
assert.ok(controls.includes("indoorMode ? 'Local beam azimuth'"), 'indoor beam azimuth is device-local');
assert.ok(controls.includes('indoor-antenna-rf-summary'), 'indoor RF summary is rendered');
assert.ok(controls.includes('tx.indoorBeamSteering?.azimuthDeg ?? 0'), 'indoor steering starts from stored device-local settings');
assert.ok(controls.includes('indoorBeamSteering: { azimuthDeg: beamsteeringAz, elevationDeg: beamsteeringEl }'), 'indoor steering updates do not overwrite outdoor angles');
assert.ok(controls.includes('scene-level TX array') && controls.includes('compatible array dimensions'), 'shared Sionna array scope and multi-device size constraint are disclosed');
assert.ok(app.includes('solverOptions={solverOptions}') && app.includes('freqGhz={freqGhz}'), 'RF state is passed to viewport');
assert.ok(types.includes("beamSteeringFrame?: 'device_local' | 'world_enu'"), 'frontend TX type retains steering frame');
assert.ok(types.includes('indoorBeamSteering?: { azimuthDeg: number; elevationDeg: number }'), 'indoor steering is stored separately from outdoor angles');
assert.ok(models.includes('beamSteeringFrame: Literal["device_local", "world_enu"]'), 'backend accepts steering frame metadata');
assert.ok(models.includes('indoorBeamSteering: Optional[IndoorBeamSteering]'), 'backend preserves indoor steering separately');
assert.ok(appSource.includes('indoorScene && (!updatedTx.sceneSessionId || updatedTx.sceneSessionId === indoorScene.sessionId)'), 'unplaced indoor TX RF edits remain scene-local');
assert.ok(appSource.includes('indoorScene && (!updatedRx.sceneSessionId || updatedRx.sceneSessionId === indoorScene.sessionId)'), 'unplaced indoor RX RF edits remain scene-local');
assert.ok(helper.includes('0.5λ') || helper.includes('spacingLambda = 0.5'), 'array uses 0.5-lambda spacing default');
assert.ok(helper.includes('getArrayElementVisualDimensions') && studio.includes('getArrayElementVisualDimensions'), 'element glyph sizes scale with physical pitch');
console.log('Antenna/RF integration source contract: PASS');
